def collect_object_rows(objects_dir: Path) -> List[Dict[str, object]]:
    """Scan the corpus directly from frontmatter -- no generated mirror involved.

    Returns one row per object: {id, title, domain (list, possibly empty),
    status, state}, sorted by id. Uses the same scan/extract pattern as
    ``collect_domain_index`` so `ws list --domain X` and `ws domain sync`
    always agree on membership.
    """
    rows: List[Dict[str, object]] = []

    for obj_file in sorted(objects_dir.rglob("*.md")):
        try:
            content = obj_file.read_text(encoding="utf-8")
        except Exception:
            continue

        raw_domain = _extract_frontmatter_field(content, _DOMAIN_LINE_RE)
        values = [v for v in parse_domain_field(raw_domain) if v in VALID_DOMAINS] if raw_domain else []

        rows.append({
            "id": _extract_frontmatter_field(content, _ID_LINE_RE) or obj_file.stem,
            "title": _extract_frontmatter_field(content, _TITLE_LINE_RE) or obj_file.stem,
            "domain": values,
            "status": _extract_frontmatter_field(content, _STATUS_LINE_RE) or "",
            "state": _extract_frontmatter_field(content, _STATE_LINE_RE) or "",
        })

    rows.sort(key=lambda row: row["id"])
    return rows


def cmd_list(args: argparse.Namespace) -> int:
    """List Work Objects, optionally filtered by domain (live frontmatter query)."""
    try:
        ws_root = _find_work_studio_root()
    except FileNotFoundError as e:
        print(f"Error: {e}", file=sys.stderr)
        return 1

    filter_domains = [d for d in (getattr(args, "domain", None) or [])]
    for value in filter_domains:
        if value not in VALID_DOMAINS:
            print(
                f"Error: invalid domain value '{value}'. Valid values: "
                f"{', '.join(sorted(VALID_DOMAINS))}",
                file=sys.stderr,
            )
            return 1

    objects_dir = ws_root / ".work-studio" / "objects"
    rows = collect_object_rows(objects_dir)

    if filter_domains:
        rows = [r for r in rows if set(r["domain"]) & set(filter_domains)]

    if not rows:
        if filter_domains:
            print(f"No Work Objects found for domain(s): {', '.join(filter_domains)}")
        else:
            print("No Work Objects found.")
        return 0

    for row in rows:
        domain_display = f"[{', '.join(row['domain'])}]" if row["domain"] else "(none)"
        print(f"{row['id']}  {row['status']}/{row['state']}  {domain_display}  {row['title']}")

    print(f"\n{len(rows)} Work Object(s).")
    return 0
